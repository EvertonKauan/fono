const paid = (
  id: string,
  tenantId: string,
  patient: Patient,
  period: string,
  sessions: number,
  paidAt: string,
  method: PaymentMethod,
): Payment => ({
  id,
  tenantId,
  patientId: patient.id,
  period,
  sessions,
  amount: sessions * patient.visit.fee,
  status: 'pago',
  paidAt,
  method,
})

const pending = (
  id: string,
  tenantId: string,
  patient: Patient,
  period: string,
  sessions: number,
): Payment => ({
  id,
  tenantId,
  patientId: patient.id,
  period,
  sessions,
  amount: sessions * patient.visit.fee,
  status: 'pendente',
})

const session = (
  n: number,
  patient: Patient,
  date: string,
  time: string,
  status: SessionStatus,
  extra: Partial<Session> = {},
): Session => ({
  id: `ses-${String(n).padStart(3, '0')}`,
  tenantId: patient.tenantId,
  patientId: patient.id,
  date,
  time,
  status,
  billing: 'particular',
  createdAt: `${date}T12:00:00.000Z`,
  updatedAt: `${date}T12:00:00.000Z`,
  ...extra,
})

