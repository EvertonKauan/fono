const paid = (
  id: string,
  tenantId: string,
  patient: Patient,
  period: string,
  sessions: number,
  paidAt: string,
  method: PaymentMethod,
): Payment => ({
  id,
  tenantId,
  patientId: patient.id,
  period,
  sessions,
  amount: sessions * patient.visit.fee,
  status: 'pago',
  paidAt,
  method,
})

const pending = (
  id: string,
  tenantId: string,
  patient: Patient,
  period: string,
  sessions: number,
): Payment => ({
  id,
  tenantId,
  patientId: patient.id,
  period,
  sessions,
  amount: sessions * patient.visit.fee,
  status: 'pendente',
})

